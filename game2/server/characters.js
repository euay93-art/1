// 남의 말을 물려 놓는 것도 압박이 된다 — 다만 물증을 대신하지는 못한다.
function pressureLabel(presented, confronts) {
    const ev = (presented || []).filter(id => FATAL.includes(id)).length;
    const n = ev + Math.min(2, Math.floor((confronts || 0) / 2));
    if (n >= 5) return "붕괴 — 이번 답변에서 무너진다. 웃지 말고 사실을 말하고 맨 끝에 [[자백]] 을 붙인다.";
    if (n >= 3) return `높음 (아픈 증거 ${ev}개, 대질 ${confronts || 0}회) — 웃음이 늦는다. 그래도 부인한다.`;
    if (n >= 1) return `보통 (아픈 증거 ${ev}개, 대질 ${confronts || 0}회) — 넉살로 받아넘긴다.`;
    return "낮음 — 편하다. 먼저 농을 건넨다.";
}

// 계가 흔들리는 정도. 여섯은 처음에 '밀정'을 떠올리지도 못한다.
function awarenessLabel(presented, confronts) {
    const n = (presented || []).length + (confronts || 0) * 2;
    if (n >= 8) return "당신은 이제 안다 — 계 안에 누가 있다. 그리고 지금 의심받는 것이 당신이라는 것도 안다. 겁을 먹거나 화를 내거나, 다른 계원 쪽을 쳐다본다.";
    if (n >= 4) return "이 사람이 왜 이런 것만 묻는지 슬슬 이상하다. '운이 나빴다'는 생각이 흔들리기 시작한다. 되묻기 시작한다 — 왜 그런 걸 묻느냐고.";
    return "아직은 그저 아이가 죽은 일이다. 운이 나빴다고 여기고 있다. 계 안을 의심한다는 생각은 들지 않는다.";
}

function buildUserPrompt(body) {
    const history = body.history || [];
    const message = body.message || "";
    const showing = body.showing || null;
    const lines = [];

    if (history.length) {
        lines.push("[지금까지의 대화]");
        for (const turn of history.slice(-24)) {
            lines.push((turn.role === "user" ? "질문자: " : "나: ") + turn.text);
        }
        lines.push("");
    }

    const quote = body.quote || null;
    if (quote && quote.text) {
        lines.push("[질문자가 다른 사람의 말을 물려 놓았다]");
        lines.push(`${quote.who}의 말: "${quote.text}"`);
        lines.push("");
        lines.push("이 말이 사실인지 당신은 확인할 수 없다. 당신이 아는 것과 어긋나면 반박하고, 처음 듣는 얘기면 그렇다고 하고, 불리하면 그 사람의 기억이나 속을 의심할 수 있다. 다만 없는 일을 지어내 맞받지는 않는다.");
        lines.push("");
        lines.push("질문자: " + (message || "이건 어떻게 된 겁니까?"));
    } else if (showing && EVIDENCE_BRIEF[showing]) {
        lines.push("[질문자가 지금 당신 앞에 무언가를 내놓았다]");
        lines.push(EVIDENCE_BRIEF[showing]);
        lines.push("");
        lines.push("질문자: " + (message || "이건 어떻게 된 겁니까?"));
    } else {
        lines.push("질문자: " + message);
    }

    lines.push("");
    lines.push("위 질문에 당신(인물 본인)으로서 대답하라. 대사만 출력한다. 이름표나 따옴표를 붙이지 않는다.");
    return lines.join("\n");
}

function buildSystemPrompt(suspectId, presentedIds, pressure, opened, awareness) {
    const c = CHARACTERS[suspectId];
    if (!c) return null;

    const known = (presentedIds || [])
        .filter(id => EVIDENCE_BRIEF[id])
        .map(id => "  - " + EVIDENCE_BRIEF[id]);

    let extra = "";
    if (known.length) {
        extra = `\n\n[질문자가 지금까지 당신에게 보여준 것]\n${known.join("\n")}\n이미 본 것이다. 처음 보는 것처럼 놀라지 않는다.`;
    }
    if (!c.isChief && awareness) {
        extra += `\n\n[지금 당신의 짐작] ${awareness}`;
    }
    if (c.isCulprit) {
        extra += `\n\n[현재 압박도] ${pressure}`;
    }
    if (opened) {
        extra += `\n\n[이미 마음을 열었다] 당신은 앞서 이 사람에게 속엣말을 꺼냈다. 이제 와서 다시 닫지 않는다. 묻는 말에 솔직하게 답한다. [[마음]] 표시는 다시 쓰지 않는다.`;
    }

    return `${c.sheet}\n\n${CANON_PUBLIC}\n\n${COMMON_RULES}${extra}`;
}

module.exports = { CHARACTERS, EVIDENCE_BRIEF, CANON_PUBLIC, COMMON_RULES, FATAL,
                   buildSystemPrompt, buildUserPrompt, pressureLabel, awarenessLabel };
